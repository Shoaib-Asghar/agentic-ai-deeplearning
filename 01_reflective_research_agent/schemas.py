"""
Data contracts for the Reflective Research Agent.

Defines the structured output schemas for:
1. Planner Agent: ToolChoice, ResearchStep, ResearchPlan
2. Researcher Agent: StepFinding, ResearchDossier
3. Editor Agent (Reflection): EditorialReview
"""

from enum import Enum
from pydantic import BaseModel, Field


class ToolChoice(str, Enum):
    """Available information retrieval tools in the research pipeline."""
    WIKIPEDIA = "wikipedia"
    ARXIV = "arxiv"
    TAVILY = "tavily"


class ResearchStep(BaseModel):
    """Represents a single step in the research plan."""
    step_number: int = Field(
        description="Sequential index of this step, starting from 1."
    )
    question: str = Field(
        description="The specific sub-question this step aims to answer."
    )
    tool: ToolChoice = Field(
        description="The tool to use: 'wikipedia' for broad background/definitions, "
                    "'arxiv' for academic papers/benchmarks, or 'tavily' for recent web info/developments."
    )
    search_query: str = Field(
        description="The precise keyword search query to pass into the selected tool."
    )
    rationale: str = Field(
        description="Brief explanation of why this question and tool were selected."
    )


class ResearchPlan(BaseModel):
    """The complete research blueprint generated by the Planner Agent."""
    topic: str = Field(
        description="The original research topic provided by the user."
    )
    strategy_overview: str = Field(
        description="High-level summary of the research strategy and how the sub-questions cover the topic."
    )
    steps: list[ResearchStep] = Field(
        description="A curated sequence of 3 to 5 targeted research steps."
    )


class StepFinding(BaseModel):
    """Synthesized evidence extracted from executing a single research step."""
    step_number: int = Field(
        description="The step number corresponding to the plan."
    )
    question: str = Field(
        description="The research question that was investigated."
    )
    tool_used: str = Field(
        description="The tool queried (wikipedia, arxiv, or tavily)."
    )
    summary: str = Field(
        description="Dense, fact-based synthesis answering the question based strictly on the retrieved data."
    )
    citations: list[str] = Field(
        description="List of verified source URLs, paper titles, or reference identifiers retrieved from the tool."
    )


class ResearchDossier(BaseModel):
    """The complete compiled research findings gathered across all plan steps."""
    topic: str = Field(
        description="The overall research topic."
    )
    findings: list[StepFinding] = Field(
        description="The sequential research findings gathered for each step."
    )


class EditorialReview(BaseModel):
    """The structured critique and polished revision produced by the Editor Agent."""
    critique_clarity: str = Field(
        description="Evaluation of the report's structural flow, technical clarity, and readability."
    )
    critique_grounding: str = Field(
        description="Evaluation of whether all technical claims align strictly with the research dossier."
    )
    critique_citations: str = Field(
        description="Evaluation of citation quality, link correctness, and reference completeness."
    )
    improvements_made: list[str] = Field(
        description="Bullet list of specific revisions applied to elevate the draft."
    )
    final_report: str = Field(
        description="The complete revised, publication-ready research report in GitHub-flavored Markdown."
    )
