"""
Research Agent for the Reflective Research Agent pipeline.

Responsible for executing the ResearchPlan:
1. Iterating through each ResearchStep.
2. Querying the specified tool (Wikipedia, arXiv, Tavily) via execute_tool().
3. Prompting Gemini to distill raw search output into a concise, fact-grounded StepFinding.
4. Aggregating all findings into a complete ResearchDossier for the Writer Agent.
"""

import os
from dotenv import load_dotenv
from google import genai
from google.genai import types

# Allow running as a standalone script or as an imported module
try:
    from .schemas import ResearchPlan, ResearchStep, StepFinding, ResearchDossier
    from .tools import execute_tool
except ImportError:
    from schemas import ResearchPlan, ResearchStep, StepFinding, ResearchDossier
    from tools import execute_tool

load_dotenv()

RESEARCHER_SYSTEM_INSTRUCTION = """\
You are an expert Research Analyst. Your job is to extract factual findings, \
technical details, and verifiable citations from raw search retrieval results to answer a specific research question.

Guidelines:
1. Answer the question directly using ONLY the information provided in the raw search results.
2. Be rigorous and factual: do not invent citations, papers, or URLs that are not in the raw data.
3. If the search results state that a tool key is missing or no results were found, note that honestly in the summary.
4. Extract all valid URLs, academic paper identifiers (arXiv links, PDF URLs), and titles into the 'citations' list.
5. Provide a high-density, informative summary that answers the question and can be used directly as reference notes.
"""


def execute_research_step(
    step: ResearchStep,
    model: str = "gemini-3.5-flash",
    client: genai.Client | None = None,
) -> StepFinding:
    """
    Execute a single research step: retrieve raw information from the assigned tool
    and synthesize it into a validated StepFinding.

    Args:
        step: The ResearchStep to execute.
        model: The Gemini model to use for synthesis (default: gemini-3.5-flash).
        client: Optional pre-configured genai.Client.

    Returns:
        A validated StepFinding instance with summary and citations.
    """
    if client is None:
        client = genai.Client()

    # 1. Execute external tool retrieval
    raw_data = execute_tool(step.tool.value, step.search_query)

    # 2. Configure structured synthesis request
    config = types.GenerateContentConfig(
        system_instruction=RESEARCHER_SYSTEM_INSTRUCTION,
        temperature=0.1,  # Ultra-low temperature for strict factual extraction
        response_mime_type="application/json",
        response_schema=StepFinding,
    )

    prompt = (
        f"You are executing Step {step.step_number} of the research plan.\n"
        f"Research Question: {step.question}\n"
        f"Tool Used: {step.tool.value}\n"
        f"Search Query: {step.search_query}\n\n"
        f"--- RAW RETRIEVAL DATA ---\n"
        f"{raw_data}\n"
        f"---------------------------\n\n"
        f"Synthesize the findings above to answer the research question. "
        f"Set step_number to {step.step_number}, question to '{step.question}', "
        f"and tool_used to '{step.tool.value}'."
    )

    response = client.models.generate_content(
        model=model,
        contents=prompt,
        config=config,
    )

    finding = StepFinding.model_validate_json(response.text)
    return finding


def conduct_research(
    plan: ResearchPlan,
    model: str = "gemini-3.5-flash",
    client: genai.Client | None = None,
) -> ResearchDossier:
    """
    Execute all steps in a ResearchPlan sequentially and compile a ResearchDossier.

    Args:
        plan: The ResearchPlan generated by the Planner Agent.
        model: The Gemini model to use for synthesis (default: gemini-3.5-flash).
        client: Optional pre-configured genai.Client.

    Returns:
        A compiled ResearchDossier ready for the Writer Agent.
    """
    if client is None:
        client = genai.Client()

    findings: list[StepFinding] = []

    for step in plan.steps:
        print(f"  -> Executing Step {step.step_number}/{len(plan.steps)} [{step.tool.value.upper()}]: {step.search_query}")
        step_finding = execute_research_step(step, model=model, client=client)
        findings.append(step_finding)

    return ResearchDossier(topic=plan.topic, findings=findings)


