"""
Editor Agent (Reflection Design Pattern) for the Reflective Research Agent pipeline.

Implements the Actor-Critic / Evaluator-Optimizer pattern:
1. Evaluates the initial report draft against a rigorous quality rubric:
   - Technical clarity and flow.
   - Factual grounding against the original ResearchDossier.
   - Citation completeness and valid Markdown link formatting.
2. Formulates explicit, structured critiques.
3. Produces a polished, publication-ready final research report.
"""

import os
import sys
from pathlib import Path
from dotenv import load_dotenv
from google import genai
from google.genai import types

# Ensure module directory is in sys.path for direct imports
sys.path.insert(0, str(Path(__file__).resolve().parent))

from schemas import ResearchDossier, StepFinding, EditorialReview
from writer import format_dossier_for_prompt

load_dotenv()

EDITOR_SYSTEM_INSTRUCTION = """\
You are a Principal Scientific Editor and Lead Research Reviewer. \
Your task is to review, critique, and elevate an initial draft of a research report \
using the provided Research Dossier as the strict ground truth.

Your Review Rubric:
1. Structural Flow & Technical Clarity:
   - Are the transitions between sections smooth and logical?
   - Is technical jargon explained clearly without unnecessary repetition?
   - Are bullet points and subheadings utilized effectively?
2. Factual Grounding & Integrity:
   - Does every substantive claim match the facts in the research dossier?
   - Eliminate any speculative generalizations or unsupported assertions.
3. Citation Completeness & Link Integrity:
   - Verify that all papers, author attributions, and URLs from the dossier are cited accurately.
   - Ensure all references are formatted with clean, clickable Markdown links ([Title](URL)).

You must populate:
- critique_clarity: Specific observations regarding flow, tone, and readability.
- critique_grounding: Verification of factual fidelity against the dossier.
- critique_citations: Review of citation accuracy and Markdown links.
- improvements_made: A list of concrete edits you made in the revision.
- final_report: The complete, revised, publication-ready research report in Markdown.
"""


def edit_and_reflect(
    draft: str,
    dossier: ResearchDossier,
    model: str = "gemini-3.5-flash",
    client: genai.Client | None = None,
) -> EditorialReview:
    """
    Critique an initial report draft against the research dossier and produce a polished revision.

    Args:
        draft: The initial Markdown draft generated by the Writer Agent.
        dossier: The original ResearchDossier (ground truth).
        model: The Gemini model to use (default: gemini-3.5-flash).
        client: Optional pre-configured genai.Client.

    Returns:
        An EditorialReview instance containing explicit critiques and the revised final report.
    """
    if client is None:
        client = genai.Client()

    dossier_text = format_dossier_for_prompt(dossier)

    prompt = (
        f"RESEARCH TOPIC: {dossier.topic}\n\n"
        f"=== GROUND TRUTH RESEARCH DOSSIER ===\n"
        f"{dossier_text}\n\n"
        f"=== INITIAL DRAFT TO REVIEW ===\n"
        f"{draft}\n\n"
        f"Perform a thorough editorial review based on the rubric. "
        f"Generate the critique and output the polished final report in final_report."
    )

    config = types.GenerateContentConfig(
        system_instruction=EDITOR_SYSTEM_INSTRUCTION,
        temperature=0.2,  # Low temperature for analytical critique and rigorous editing
        response_mime_type="application/json",
        response_schema=EditorialReview,
    )

    response = client.models.generate_content(
        model=model,
        contents=prompt,
        config=config,
    )

    if not response.text:
        raise ValueError("Editor agent received an empty response from Gemini.")

    review = EditorialReview.model_validate_json(response.text)
    return review


if __name__ == "__main__":
    print("=" * 70)
